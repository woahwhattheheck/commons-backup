"""host/sdc_doom_render.py — DOOM build 04: the RENDER is a stored circuit too. No host geometry. (owner 07-16)

The renderer is no longer host JS trig/DDA. The whole visible-surface computation is ONE stored gate-net in titan.gguf,
addressed per screen column: address = (px, py, angle, column) -> (wall-distance, texture-U, wall-side), GENERATED by the
stored gates (a fixed-depth unrolled ray-march, direction from a stored trig ROM, walls from a stored map ROM). This is
docs/SDC_ADDRESSING.md verbatim: the address is the input, the stored circuit is the function, the addressed read is the
output. The host container only ripples the circuit across the columns and blits pixels — it computes no geometry.

Everything is verified byte-exact against a Python reference that performs the identical integer march, then stored in
titan.gguf and exported into a self-contained double-click HTML that ripples the same gate arrays.

  python host/sdc_doom_render.py
"""
