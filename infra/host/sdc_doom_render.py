# ---- the level ----
def make_map():
    g = [['.'] * N for _ in range(N)]
    for i in range(N): g[0][i]=g[N-1][i]=g[i][0]=g[i][N-1]='#'
    for (r0,c0,r1,c1) in [(2,2,4,4),(2,11,4,13),(11,2,13,4),(11,11,13,13),(6,6,9,9)]:
        for r in range(r0,r1+1):
            for c in range(c0,c1+1): g[r][c]='#'
    return ["".join(r) for r in g]
MAP = make_map()
WALLTAB = [ (1 if MAP[(idx>>4)&15][idx&15]=='#' else 0) for idx in range(256) ]   # cellIdx = cx | cy<<4

# ---- precomputed integer trig tables (the SAME values feed the ROM and the reference, so they match by construction) ----
def _sgn12(v): return v & 0xFFF                       # 12-bit two's complement
COS = [ _sgn12(int(round(math.cos(a/256*2*math.pi)*1024))) for a in range(256) ]
SIN = [ _sgn12(int(round(math.sin(a/256*2*math.pi)*1024))) for a in range(256) ]
OFF = [ (int(round((col-NCOL//2)/NCOL*FOV_U))) & 0xFF for col in range(NCOL) ]      # per-column ray-angle offset (8-bit)

# ================= reference march (integer, bit-exact with the circuit) =================
def ref_cast(px, py, angle, col):
    ra = (angle + OFF[col]) & 0xFF
    dx = COS[ra]; dy = SIN[ra]
    dxs = dx - 4096 if dx & 0x800 else dx             # sign-extend 12-bit
    dys = dy - 4096 if dy & 0x800 else dy
    x = (px << 6) & 0x3FFFF; y = (py << 6) & 0x3FFFF   # 18-bit Q6 position
    hit = STEPS - 1; found = 0; texu = 0; side = 0
    for s in range(STEPS):
        x = (x + dxs) & 0x3FFFF; y = (y + dys) & 0x3FFFF
        ux = x >> 6; uy = y >> 6                       # 12-bit unit coords
        oor = 1 if (ux >= 1024 or uy >= 1024) else 0
        cx = (ux >> 6) & 15; cy = (uy >> 6) & 15
        wall = 1 if oor else WALLTAB[cx | (cy << 4)]
        first = wall & (1 - found)
        if first:
            hit = s
            side = 1 if abs(dxs) >= abs(dys) else 0    # dominant axis => which wall face (for texture + shading)
            texu = (uy if side else ux) & 63
            found = 1
    return hit, texu, side

# ================= the same march as ONE stored gate-net =================
def rom(c, addr, table, outbits):
    """address (LSB-first bit list) -> outbits, as a balanced mux tree (a stored function table)."""
    res = []
    for bit in range(outbits):
        cur = [c.C1 if (table[i] >> bit) & 1 else c.C0 for i in range(1 << len(addr))]
        for a in addr:
            cur = [c.mux(a, cur[k], cur[k+1]) for k in range(0, len(cur), 2)]   # mux(s,x,y)=s?y:x
        res.append(cur[0])
    return res

def _addv(c, xs, ys):                                  # add two equal-width vectors, mod 2^n (drops final carry)
    return c.add(xs, ys)

def build_raycast():
    """(px:10, py:10, angle:8, col:7) -> (hit:6, texu:6, side:1). unrolled STEPS-deep ray-march, all gates."""
    c = TC.Circuit(10 + 10 + 8 + 7); i = c.IN
    px, py, angle, col = i[0:10], i[10:20], i[20:28], i[28:35]
    ra = c.add(angle, rom(c, col, OFF, 8))[:8]         # ray angle = player angle + per-column offset
    dcos = rom(c, ra, COS, 12); dsin = rom(c, ra, SIN, 12)
    dxs = dcos + [dcos[11]] * 6                         # sign-extend 12 -> 18
    dys = dsin + [dsin[11]] * 6
    x = ([c.C0]*6 + px + [c.C0]*2)[:18]                 # px << 6 into 18-bit Q6 (px is 10-bit units)
    y = ([c.C0]*6 + py + [c.C0]*2)[:18]
    sb = SIDE_BIT(c, dxs, dys)                          # wall face is fixed per column (dir constant) -> compute ONCE
    found = c.C0; hit = c.cvec(STEPS - 1, 6); texu = [c.C0]*6; side = c.C0
    for s in range(STEPS):
        x = _addv(c, x, dxs); y = _addv(c, y, dys)
        ux = x[6:18]; uy = y[6:18]                      # 12-bit unit coords
        oor = c.or_(c.or_(ux[10], ux[11]), c.or_(uy[10], uy[11]))
        cell = ux[6:10] + uy[6:10]                     # 8-bit cellIdx = cx | cy<<4
        wall = c.or_(oor, rom(c, cell, WALLTAB, 1)[0])
        first = c.and_(wall, c.not_(found))
        svec = c.cvec(s, 6)
        hit = [c.mux(first, hit[k], svec[k]) for k in range(6)]      # latch step on first hit
        tux = [c.mux(sb, ux[k], uy[k]) for k in range(6)]           # sb ? uy : ux  (matches the reference)
        texu = [c.mux(first, texu[k], tux[k]) for k in range(6)]
        side = c.mux(first, side, sb)
        found = c.or_(found, wall)
    return c, hit + texu + [side]

def SIDE_BIT(c, dxs, dys):
    """1 if |dx| >= |dy| (x-dominant wall). abs via sign; compare magnitudes via the subtract's carry-out."""
    return _cmp_ge(c, _absv(c, dxs), _absv(c, dys))

def _absv(c, v):
    sign = v[len(v)-1]
    neg = c.add([c.not_(b) for b in v], c.cvec(1, len(v)))    # -v
    return [c.mux(sign, v[k], neg[k]) for k in range(len(v))]

def _cmp_ge(c, a, b):
    """1 if a >= b (unsigned), via full-width subtract carry-out."""
    nb = [c.not_(x) for x in b]
    out = []; carry = c.C1
    for k in range(len(a)):
        axb = c.xor(a[k], nb[k]); out.append(c.xor(axb, carry))
        carry = c.or_(c.and_(a[k], nb[k]), c.and_(axb, carry))
    return carry                                             # carry-out set => a >= b

# ---- movement (16-bit, same as build 03) ----
def wall16(wx, wy):
    cx=(wx&0xffff)//CELL; cy=(wy&0xffff)//CELL
    if cx<0 or cy<0 or cx>=N or cy>=N: return 1
    return 1 if MAP[cy][cx]=='#' else 0
def build_move():
    c=TC.Circuit(16+16+16+16+1+1+8+1+1); i=c.IN
    px,py,dx,dy=i[0:16],i[16:32],i[32:48],i[48:64]; wx,wy=i[64],i[65]; ang=i[66:74]; tl,tr=i[74],i[75]
    cxx=c.add(px,dx); cyy=c.add(py,dy)
    nx=[c.mux(wx,cxx[k],px[k]) for k in range(16)]; ny=[c.mux(wy,cyy[k],py[k]) for k in range(16)]
    ar=c.add(ang,c.cvec(MTURN,8)); n1=[c.mux(tr,ang[k],ar[k]) for k in range(8)]
    n1l=c.add(n1,c.cvec((256-MTURN)&0xff,8)); na=[c.mux(tl,n1[k],n1l[k]) for k in range(8)]
    return c, nx+ny+na
def _packm(px,py,dx,dy,wx,wy,ang,tl,tr):
    return TC.bits(px&0xffff,16)+TC.bits(py&0xffff,16)+TC.bits(dx&0xffff,16)+TC.bits(dy&0xffff,16)+[wx,wy]+TC.bits(ang&0xff,8)+[tl,tr]
def stepm(cir,px,py,ang,keys):
    mv=(1 if 'fwd' in keys else 0)-(1 if 'back' in keys else 0); rad=ang/256*2*math.pi
    dx=int(round(math.cos(rad)*MSPEED))*mv; dy=int(round(math.sin(rad)*MSPEED))*mv
    wx=wall16(px+dx,py); wy=wall16(px,py+dy); tl=1 if 'left' in keys else 0; tr=1 if 'right' in keys else 0
    o=TC.ripple(cir,_packm(px,py,dx,dy,wx,wy,ang,tl,tr)); return TC.frombits(o[0:16]),TC.frombits(o[16:32]),TC.frombits(o[32:40])
def _refm(px,py,ang,keys):
    mv=(1 if 'fwd' in keys else 0)-(1 if 'back' in keys else 0); rad=ang/256*2*math.pi
    dx=int(round(math.cos(rad)*MSPEED))*mv; dy=int(round(math.sin(rad)*MSPEED))*mv
    wx=wall16(px+dx,py); wy=wall16(px,py+dy); nx=px if wx else (px+dx)&0xffff; ny=py if wy else (py+dy)&0xffff
    a=ang
    if 'right' in keys:a=(a+MTURN)&0xff
    if 'left' in keys:a=(a-MTURN)&0xff
    return nx&0xffff,ny&0xffff,a

def cjson(name):
    c=TC.load(name); return {"nin":c["n_in"],"nw":c["n_wire"],"ga":c["ga"],"gb":c["gb"],"outs":c["outs"]}

def rip(cd, inbits):
    v=[0]*cd["nw"]; v[1]=1
    for j in range(cd["nin"]): v[2+j]=inbits[j]&1
    b=2+cd["nin"]
    for i in range(len(cd["ga"])): v[b+i]=1-(v[cd["ga"][i]]&v[cd["gb"][i]])
    return [0 if o==0 else 1 if o==1 else v[o] for o in cd["outs"]]

def main():
    print("building the RAYCAST circuit (unrolled ray-march as gates)...", flush=True)
    rc, routs = build_raycast(); ri = TC.store("doom_raycast", rc, routs, slot=6)
    mv, mouts = build_move();    mi = TC.store("doom_move16b", mv, mouts, slot=4)
    RC = cjson("doom_raycast"); MV = cjson("doom_move16b")
    print(f"stored: raycast {ri['gates']} gates, movement {mi['gates']} gates in titan.gguf.", flush=True)

    # verify the RAYCAST circuit == reference march, byte-exact
    import random; random.seed(5); okc=True; ncases=300
    for _ in range(ncases):
        px=random.randint(1,1022); py=random.randint(1,1022); ang=random.randint(0,255); col=random.randint(0,NCOL-1)
        inb=TC.bits(px,10)+TC.bits(py,10)+TC.bits(ang,8)+TC.bits(col,7)
        o=rip(RC,inb); got=(TC.frombits(o[0:6]),TC.frombits(o[6:12]),o[12])
        ref=ref_cast(px,py,ang,col)
        if got!=ref: okc=False; print("  RAYCAST MISMATCH",px,py,ang,col,"got",got,"ref",ref); break
    print(f"[verify] raycast circuit-in-params == reference march over {ncases} cases: {okc}", flush=True)
    # verify movement
    random.seed(6); okm=True
    for _ in range(800):
        px=random.randint(0,1023); py=random.randint(0,1023); ang=random.randint(0,255)
        keys=set(k for k in ('fwd','back','left','right') if random.random()<0.5)
        if stepm(TC.load("doom_move16b"),px,py,ang,keys)!=_refm(px,py,ang,keys): okm=False; break
    print(f"[verify] movement circuit == reference over 800 cases: {okm}", flush=True)
    if not (okc and okm): print("verify FAILED — not exporting."); raise SystemExit(1)

    cfg={"N":N,"CELL":CELL,"NCOL":NCOL,"STEPS":STEPS,"SPEED":MSPEED,"TURN":MTURN,"START":list(START),
         "RC":RC,"MV":MV,"rcGates":ri['gates'],"mvGates":mi['gates']}
    html=PAGE.replace("/*__DATA__*/",json.dumps(cfg))
    os.makedirs(BUILD,exist_ok=True)
    for p in (OUT, os.path.join(BUILD,"DOOM.html")):
        open(p,"w",encoding="utf-8").write(html)
    print(f"wrote {OUT}  ({len(html):,} bytes)", flush=True)
    print(f"also saved to {BUILD}\\DOOM.html", flush=True)
    print("the render is now the stored circuit — the host only addresses it and blits.", flush=True)


